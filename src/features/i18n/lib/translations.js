  if (match) return `Описание должно быть не длиннее ${match[1]} символов`;

  match = /^Folder name must be\s+(\d+)\s+characters or less$/i.exec(value);
  if (match) return `Название папки должно быть не длиннее ${match[1]} символов`;

  match = /^Level\s+(\d+)$/i.exec(value);
  if (match) return `Уровень ${match[1]}`;

  match = /^Lv\.\s*(\d+)$/i.exec(value);
  if (match) return `Ур. ${match[1]}`;

  match = /^Task\s+(\d+)$/i.exec(value);
  if (match) return `Задание ${match[1]}`;

  match = /^Task\s+(\d+):\s+flashcards$/i.exec(value);
