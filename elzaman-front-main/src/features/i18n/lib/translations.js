function pluralRu(value, one, few, many) {
  const count = Math.abs(Number(value) || 0);
  const mod10 = count % 10;
  const mod100 = count % 100;

  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

function translateDynamicRu(value) {
  let match;

  match = /^(\d+)\s+day(s)?$/i.exec(value);
  if (match) {
    const count = Number(match[1]);
    return `${count} ${pluralRu(count, 'день', 'дня', 'дней')}`;
  }

  match = /^(\d+)\s+songs$/i.exec(value);
  if (match) {
    const count = Number(match[1]);
    return `${count} ${pluralRu(count, 'песня', 'песни', 'песен')}`;
  }

  match = /^(\d+)\s+cards$/i.exec(value);
  if (match) {
    const count = Number(match[1]);
    return `${count} ${pluralRu(count, 'карточка', 'карточки', 'карточек')}`;
  }

  match = /^Level\s+(\d+)$/i.exec(value);
  if (match) return `Уровень ${match[1]}`;

  match = /^Lv\.\s*(\d+)$/i.exec(value);
  if (match) return `Ур. ${match[1]}`;

  match = /^Year:\s*(.+)$/i.exec(value);
  if (match) return `Год: ${match[1]}`;

  match = /^Duration:\s*(.+)$/i.exec(value);
  if (match) return `Длительность: ${match[1]}`;

  match = /^Added:\s*(.+)$/i.exec(value);
  if (match) return `Добавлено: ${match[1]}`;

  match = /^Member since\s+(.+)$/i.exec(value);
  if (match) return `С нами с ${match[1]}`;

  match = /^Current streak:\s*(.+)$/i.exec(value);
  if (match) return `Текущая серия: ${match[1]}`;

  match = /^Showing\s+(\d+)(\+?)\s+cards$/i.exec(value);
  if (match) return `Показано карточек: ${match[1]}${match[2]}`;

  match = /^Level\s+(\d+),\s*(\d+)\s+XP to next level$/i.exec(value);
  if (match) return `Уровень ${match[1]}, ${match[2]} XP до следующего уровня`;

  match = /^(\d+)\s+XP to Lv\.\s+(\d+)$/i.exec(value);
  if (match) return `${match[1]} XP до ур. ${match[2]}`;

  match = /^YouTube player for\s+(.+)$/i.exec(value);
  if (match) return `YouTube-плеер для ${match[1]}`;

  match = /^YouTube player:\s+(.+)$/i.exec(value);
  if (match) return `YouTube-плеер: ${match[1]}`;

  match = /^Open actions for\s+(.+)$/i.exec(value);
  if (match) return `Открыть действия для ${match[1]}`;

  match = /^(.+)\s+avatar$/i.exec(value);
  if (match) return `Аватар ${match[1]}`;

  match = /^Add\s+"(.+)"\s+to playlist$/i.exec(value);
  if (match) return `Добавить "${match[1]}" в плейлист`;

  match = /^Song\s+(.+)\s+is already added$/i.exec(value);
  if (match) return `Песня ${match[1]} уже добавлена`;

  match = /^Adding\s+(.+)$/i.exec(value);
  if (match) return `Добавление ${match[1]}`;

  match = /^Remove\s+"(.+)"\s+from this playlist\?$/i.exec(value);
  if (match) return `Удалить "${match[1]}" из этого плейлиста?`;

  match = /^This will remove\s+"(.+)"\s+from your library\.$/i.exec(value);
  if (match) return `Это удалит "${match[1]}" из вашей библиотеки.`;

  match = /^This will remove\s+"(.+)"\s+and all cards inside it\.$/i.exec(value);
  if (match) return `Это удалит "${match[1]}" и все карточки внутри.`;

  match = /^Accuracy:\s*(.+)\s+·\s+Errors:\s*(.+)\s+·\s+Checks:\s*(.+)$/i.exec(value);
  if (match) return `Точность: ${match[1]} · Ошибки: ${match[2]} · Проверки: ${match[3]}`;

  match = /^(\d+)\/(\d+)\s+correct\s+·\s+(\d+)\/(\d+)\s+connected$/i.exec(value);
  if (match) return `${match[1]}/${match[2]} верно · ${match[3]}/${match[4]} соединено`;

  match = /^(\d+)\/(\d+)\s+correct$/i.exec(value);
  if (match) return `${match[1]}/${match[2]} верно`;

  return null;
}

function interpolate(template, values) {
  if (!values || typeof values !== 'object') return template;

  return Object.entries(values).reduce((result, [key, value]) => {
    const pattern = new RegExp(`{{\\s*${key}\\s*}}`, 'g');
    return result.replace(pattern, String(value));
  }, template);
}

export function translateLiteral(value, language = 'en', values) {
  if (typeof value !== 'string') return '';
  if (language !== 'ru') return interpolate(value, values);

  const normalizedValue = value.replace(/\u00a0/g, ' ');

  const direct = RU_TRANSLATIONS[value] ?? RU_TRANSLATIONS[normalizedValue];
  if (direct) return interpolate(direct, values);

  const dynamic = translateDynamicRu(normalizedValue);
  if (dynamic) return interpolate(dynamic, values);

  return interpolate(value, values);
}
